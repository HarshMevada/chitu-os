#!/usr/bin/env python3
"""Make a 1-bpp LVGL font from a TTF/OTF for any set of characters (sparse).

usage: glyph_font.py <font.otf> <out.c> <pixel_size> <symbol_name> <chars|ascii>[+extra]

  chars "ascii" = printable ASCII; "ascii+°" adds the degree sign, etc.
  Example: glyph_font.py Inter-Bold.otf chitu_info_font.c 24 chitu_info_font "ascii+°"
"""
import sys
from PIL import Image, ImageDraw, ImageFont

src, out, size, name, spec = sys.argv[1], sys.argv[2], int(sys.argv[3]), sys.argv[4], sys.argv[5]
chars = ""
if spec.startswith("ascii"):
    chars = "".join(chr(c) for c in range(0x20, 0x7F)) + spec[len("ascii") + 1:]
else:
    chars = spec
cps = sorted(set(ord(c) for c in chars))
font = ImageFont.truetype(src, size)
ascent, descent = font.getmetrics()
bitmap, gdsc = [], ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}"]
for cp in cps:
    ch = chr(cp)
    adv = int(round(font.getlength(ch)))
    bb = font.getbbox(ch)
    if cp == 0x20 or bb[2] <= bb[0]:
        gdsc.append(f"    {{.bitmap_index = {len(bitmap)}, .adv_w = {adv * 16}, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}}")
        continue
    l, t, r, b = bb
    w, h = r - l, b - t
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255)
    bits = [1 if img.getpixel((x, y)) > 110 else 0 for y in range(h) for x in range(w)]
    bits += [0] * (-len(bits) % 8)
    idx = len(bitmap)
    bitmap += [int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8)]
    gdsc.append(f"    {{.bitmap_index = {idx}, .adv_w = {adv * 16}, .box_w = {w}, .box_h = {h}, .ofs_x = {l}, .ofs_y = {ascent - b}}}")
first = cps[0]
offsets = [cp - first for cp in cps]
with open(out, "w") as o:
    o.write(f"""// Generated by tools/glyph_font.py ({src.split('/')[-1]}, {size}px, 1 bpp, {len(cps)} glyphs)
#include <lvgl.h>

static const uint8_t glyph_bitmap[] = {{ {", ".join(hex(x) for x in bitmap)} }};
static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{(","+chr(10)).join(gdsc)}
}};
static const uint16_t unicode_list[] = {{ {", ".join(hex(x) for x in offsets)} }};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = {first:#x}, .range_length = {offsets[-1] + 1}, .glyph_id_start = 1,
     .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = {len(cps)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}},
}};
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL,
    .kern_scale = 0, .cmap_num = 1, .bpp = 1, .kern_classes = 0, .bitmap_format = 0,
}};
const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent}, .base_line = {descent}, .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = 0, .underline_thickness = 0, .dsc = &font_dsc,
}};
""")
print(name, ascent + descent, "px line,", len(cps), "glyphs,", len(bitmap), "bytes")
