#!/usr/bin/env python3
"""Make the big clock font (digits and ':') as a 1-bpp LVGL font.

usage: digits_font.py <font.ttf/otf> <out.c> <pixel_height>
"""
import sys
from PIL import Image, ImageDraw, ImageFont

src, out, size = sys.argv[1], sys.argv[2], int(sys.argv[3])
chars = "0123456789:"
font = ImageFont.truetype(src, size)
ascent, descent = font.getmetrics()
line_h = ascent + descent
glyphs = []
for ch in chars:
    l, t, r, b = font.getbbox(ch)
    w, h = max(1, r - l), max(1, b - t)
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255)
    px = [[1 if img.getpixel((x, y)) > 110 else 0 for x in range(w)] for y in range(h)]
    adv = int(round(font.getlength(ch)))
    glyphs.append((ord(ch), w, h, l, ascent - b, adv, px))  # ofs_y measured from baseline up

bitmap, gdsc = [], ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}"]
for cp, w, h, ox, oy, adv, px in glyphs:
    idx = len(bitmap)
    bits = [v for row in px for v in row]
    bits += [0] * (-len(bits) % 8)
    bitmap += [int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8)]
    gdsc.append(f"    {{.bitmap_index = {idx}, .adv_w = {adv * 16}, .box_w = {w}, .box_h = {h}, .ofs_x = {ox}, .ofs_y = {oy}}}")
cps = [g[0] for g in glyphs]
with open(out, "w") as o:
    o.write(f"""// Generated by tools/digits_font.py ({src.split('/')[-1]}, {size}px, 1 bpp): clock digits only
#include <lvgl.h>

static const uint8_t glyph_bitmap[] = {{ {", ".join(hex(b) for b in bitmap)} }};
static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{(","+chr(10)).join(gdsc)}
}};
static const uint16_t unicode_list[] = {{ {", ".join(hex(c - cps[0]) for c in cps)} }};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = {cps[0]:#x}, .range_length = {cps[-1] - cps[0] + 1}, .glyph_id_start = 1,
     .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = {len(cps)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}},
}};
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL,
    .kern_scale = 0, .cmap_num = 1, .bpp = 1, .kern_classes = 0, .bitmap_format = 0,
}};
const lv_font_t chitu_clock_font = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {line_h}, .base_line = {descent}, .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = 0, .underline_thickness = 0, .dsc = &font_dsc,
}};
""")
print(len(glyphs), "glyphs", len(bitmap), "bytes, line height", line_h)
# preview
if "--preview" in sys.argv:
    for cp, w, h, ox, oy, adv, px in glyphs[:2] + glyphs[-1:]:
        print(chr(cp), w, h, ox, oy, adv)
        print("\n".join("".join("#" if v else "." for v in r) for r in px))
