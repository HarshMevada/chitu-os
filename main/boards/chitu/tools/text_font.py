#!/usr/bin/env python3
"""Make a 1-bpp LVGL font from a TTF/OTF for printable ASCII (messages on the OLED).

usage: text_font.py <font.otf> <out.c> <pixel_size> <symbol_name>
"""
import sys
from PIL import Image, ImageDraw, ImageFont

src, out, size, name = sys.argv[1], sys.argv[2], int(sys.argv[3]), sys.argv[4]
font = ImageFont.truetype(src, size)
ascent, descent = font.getmetrics()
first, last = 0x20, 0x7E
bitmap, gdsc = [], ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}"]
for cp in range(first, last + 1):
    ch = chr(cp)
    adv = int(round(font.getlength(ch)))
    bb = font.getbbox(ch)
    if cp == 0x20 or bb[2] <= bb[0]:
        gdsc.append(f"    {{.bitmap_index = {len(bitmap)}, .adv_w = {adv * 16}, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}}")
        continue
    l, t, r, b = bb
    w, h = r - l, b - t
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255)
    bits = [1 if img.getpixel((x, y)) > 100 else 0 for y in range(h) for x in range(w)]
    bits += [0] * (-len(bits) % 8)
    idx = len(bitmap)
    bitmap += [int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8)]
    gdsc.append(f"    {{.bitmap_index = {idx}, .adv_w = {adv * 16}, .box_w = {w}, .box_h = {h}, .ofs_x = {l}, .ofs_y = {ascent - b}}}")
with open(out, "w") as o:
    o.write(f"""// Generated by tools/text_font.py ({src.split('/')[-1]}, {size}px, 1 bpp, ASCII)
#include <lvgl.h>

static const uint8_t glyph_bitmap[] = {{ {", ".join(hex(x) for x in bitmap)} }};
static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{(","+chr(10)).join(gdsc)}
}};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = {first:#x}, .range_length = {last - first + 1}, .glyph_id_start = 1,
     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}},
}};
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL,
    .kern_scale = 0, .cmap_num = 1, .bpp = 1, .kern_classes = 0, .bitmap_format = 0,
}};
const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent}, .base_line = {descent}, .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = 0, .underline_thickness = 0, .dsc = &font_dsc,
}};
""")
print(name, ascent + descent, "px line,", len(bitmap), "bytes")
